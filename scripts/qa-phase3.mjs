import {chromium} from "playwright-core";
import path from "node:path";
const base="http://127.0.0.1:3026";
const errors=[];
function check(condition,label){if(!condition)errors.push(label);console.log(label,condition?"PASS":"FAIL");}
const browser=await chromium.launch({executablePath:"C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",headless:true,args:["--no-sandbox"]});
try {
 const context=await browser.newContext({viewport:{width:390,height:844},permissions:["clipboard-read","clipboard-write"]});
 const page=await context.newPage();
 page.on("pageerror",e=>errors.push("PAGE_ERROR "+e.message));
 await page.goto(base+"/",{waitUntil:"networkidle"});
 check(await page.locator(".intent-editor textarea").count()===1,"INTENT_INPUT");
 await page.locator(".intent-editor textarea").fill("我想把網站變得更漂亮，有動畫");
 await page.locator(".intent-submit").click();
 check(await page.locator(".intent-result").count()>0,"INTENT_RESULTS");
 check((await page.locator(".intent-result").first().innerText()).includes("Skill")||(await page.locator(".intent-result").first().innerText()).length>20,"INTENT_REASON");
 await page.locator(".intent-editor textarea").fill("我家蘋果樹要澆幾多雨水");
 await page.locator(".intent-submit").click();
 check(await page.locator(".intent-empty").isVisible(),"UNKNOWN_INTENT_EMPTY");
 const languageSwitch=page.locator(".language-switch button");
 await languageSwitch.last().click();
 check(await page.locator("html").getAttribute("lang")==="zh-Hans","LANG_HANS");
 check((await page.locator("#intent-title").innerText()).includes("名称"),"SIMPLIFIED_HOME");
 await page.reload({waitUntil:"networkidle"});
 check(await page.locator("html").getAttribute("lang")==="zh-Hans","LANG_PERSISTED");
 await page.locator(".hero-search input").fill("网站");
 check(await page.locator(".skill-card").count()>0,"SIMPLIFIED_SEARCH");
 const dims=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth}));
 check(dims.width===dims.scrollWidth,"MOBILE_WIDTH");
 await page.screenshot({path:path.join(process.env.USERPROFILE,"Desktop","skill-atlas-zh","docs","qa-phase3-mobile.png"),fullPage:true});
 await page.goto(base+"/skills/frontend-design",{waitUntil:"networkidle"});
 check((await page.locator("h1").first().innerText()).includes("设计"),"SIMPLIFIED_DETAIL_TITLE");
 await page.getByRole("button",{name:"复制指令"}).click();
 const cmd=await page.evaluate(()=>navigator.clipboard.readText());
 check(cmd==="npx skills add anthropics/skills --skill frontend-design","INSTALL_COMMAND_UNMODIFIED");
 await page.getByRole("button",{name:"复制示例"}).click();
 const example=await page.evaluate(()=>navigator.clipboard.readText());
 check(example.includes("网站")||example.includes("设计"),"SIMPLIFIED_EXAMPLE_COPY");
 await page.goto(base+"/discoveries",{waitUntil:"networkidle"});
 check(await page.locator(".candidate-card").count()===20,"CANDIDATES_SEPARATE_20");
 check(await page.locator(".candidate-card .copy-button").count()===0,"NO_CANDIDATE_INSTALL");
 await page.screenshot({path:path.join(process.env.USERPROFILE,"Desktop","skill-atlas-zh","docs","qa-phase3-candidates.png"),fullPage:true});
 const missing=await page.goto(base+"/skills/nonexistent-123",{waitUntil:"networkidle"});
 check(missing.status()===404,"NOT_FOUND_404");
 await page.setViewportSize({width:1440,height:900});
 await page.goto(base+"/",{waitUntil:"networkidle"});
 check(await page.evaluate(()=>innerWidth===document.documentElement.scrollWidth),"DESKTOP_WIDTH");
 await page.screenshot({path:path.join(process.env.USERPROFILE,"Desktop","skill-atlas-zh","docs","qa-phase3-desktop.png"),fullPage:true});
 console.log("ERRORS",JSON.stringify(errors));
 if(errors.length)process.exitCode=1;
}finally{await browser.close()}
